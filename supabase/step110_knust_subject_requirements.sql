, alt as (insert into public.program_requirements (program_id,subject,min_grade,is_core,any_of_group,any_of_need)
  select k.id,x.s,'C6',false,1,1 from k join (values ('BSc Agricultural Engineering','Chemistry'),('BSc Agricultural Engineering','Biology'),('BSc Geomatic (Geodetic) Engineering','Chemistry'),('BSc Geomatic (Geodetic) Engineering','Geography'),('BSc Biomedical Engineering','Chemistry'),('BSc Biomedical Engineering','Biology')) x(n,s) on x.n=k.name returning 1)

, ins as (insert into public.program_requirements (program_id,subject,min_grade,is_core,any_of_group,any_of_need)
  select k.id,v.subject,v.min_grade,false,v.grp,v.need from v join k on k.name=v.name
  where not exists (select 1 from public.program_requirements r where r.program_id=k.id and r.subject=v.subject and r.is_core=false) returning 1)
select (select count(*) from del) del,(select count(*) from alt) alt,(select count(*) from ins) ins;
