  insert into public.programs (school_id, name, level, field, mode, verified, demo, entry_note)
  select s.id, v.name, 'Diploma', v.field, v.mode, false, false,
   case when v.kind = 'h' then 'Entry rule (CCTU 2025/2026 admission notice, https://cctu.edu.gh/site/cms/app/uploads/doc/6035312.pdf): WASSCE six passes (A1 to D7) including English Language, Mathematics and Social Studies or Science, with at least C6 in three relevant electives. No HND cut-off or aggregate is stated. No campus is stated. Other routes (technical, vocational, business certificates) are in the notice.' when v.kind = 'd' then 'Entry rule (CCTU 2025/2026 admission notice, https://cctu.edu.gh/site/cms/app/uploads/doc/6035312.pdf): four passes in SSSCE, WASSCE or GBCE including English Language and Core Mathematics. No cut-off or aggregate is stated. The notice gives no mode or campus, so Regular is assumed.' end
