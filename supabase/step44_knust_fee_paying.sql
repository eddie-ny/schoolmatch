src as (
  select p.*, v.fee, gen_random_uuid() as new_id from public.programs p join public.schools s on s.id = p.school_id
  join v on v.name = p.name
  where s.name = 'Kwame Nkrumah University of Science and Technology' and p.level = 'Undergraduate' and p.mode = 'Regular' and p.campus is null
    and not exists (select 1 from public.programs q where q.school_id = p.school_id and q.name = p.name and q.level = p.level and q.mode = 'Fee-paying')),
ins as (
  insert into public.programs (id, school_id, name, level, field, fees_ghs, duration_years, english_test_waiver, foundation_available, verified, demo, group_name, min_degree_class, entry_note, mode, campus)
  select new_id, school_id, name, level, field, fee, duration_years, english_test_waiver, foundation_available, true, demo, group_name, min_degree_class,
         'Fee-paying programme. The fee is the total in KNUST''s provisional 2025/2026 fee schedule for fee-paying freshmen. KNUST has not published a separate fee-paying cut-off, and the subject requirements are copied from the regular programme, so confirm both with the school.', 'Fee-paying', campus from src returning id),
rq as (
  insert into public.program_requirements (program_id, subject, min_grade, is_core)
  select s.new_id, r.subject, r.min_grade, r.is_core from src s join public.program_requirements r on r.program_id = s.id returning 1)
select (select count(*) from ins) as programs, (select count(*) from rq) as requirements;
